    recs = parse_order_pdf_text(doc, "квоты")
    assert len(recs) == 2
    physics = recs[1]
    assert physics["unit"] == "Институт физики, технологии и информационных систем"
    assert physics["direction"] == "03.03.02 Физика. Фундаментальная физика и прорывные технологии"
    assert physics["quota_kind"] == "отдельная"
    assert physics["count"] == 3
