def route(text: str) -> Tuple[str, str]:
    """Возвращает (intent, payload). intent: start|help|menu|calc|spisok|dates|free."""
    t = (text or "").strip()
    cmd = t.split()[0].lower().split("@")[0] if t else ""
    if cmd in ("/start",):
        return ("start", "")
    if cmd in ("/help",):
        return ("help", "")
    if cmd in ("/abitur", "/menu", "/faq"):
        return ("menu", "")
    if cmd in ("/bally", "/ball", "/calc"):
        return ("calc", "")
    if cmd in ("/spisok", "/list", "/spiski"):
        arg = t[len(t.split()[0]):].strip() if t else ""
        return ("spisok", arg)
    if cmd in ("/sroki", "/dates"):
        return ("dates", "")
    return ("free", t)
